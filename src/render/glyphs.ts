/**
 * AFTERBURN DISPLAY — a bespoke monoline typeface, drawn as stroked polylines.
 *
 * Why not a webfont: an installed system face is whatever the judge's machine
 * happens to have, and a downloaded one is a network request that can fail on
 * an itch.io iframe. Vectors ship inside the bundle, look identical everywhere,
 * scale to any size without hinting artefacts, and — the actual reason — can be
 * *drawn on progressively*, which is where the title sequence comes from.
 *
 * Design: geometric, monoline, all-caps, with 45° chamfers instead of curves.
 * Tabular by construction — every digit has the same advance — so a score
 * counter never jitters as it climbs.
 *
 * Coordinates: x rightward from 0, y downward with 0 = cap line and 1 = the
 * baseline. Each polyline is a flat [x0,y0,x1,y1,...] run.
 */

